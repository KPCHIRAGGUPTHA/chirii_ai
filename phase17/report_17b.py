"""
Phase 17B — Tables for Foundation v4 base and the PASS/FAIL verdict under phase17/CRITERIA_17B.md, applied exactly as
committed. Uses Phase 18's own result loading and metric choices (phase18/report.py) and subset scores
(phase18/subset_scores.py), so v4, GPT-2 and MiniGPT 34M base are read identically.

Writes phase17/results/criteria_17b.json and phase17/results/TABLES_17B.md.

Usage (from the repository root):  python phase17/report_17b.py
"""

import json
import math
import os
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, os.path.join(ROOT, "phase18"))

import report as r18  # noqa: E402  (phase18/report.py)

V4, GPT2, M34 = "minigpt_v4_base", "gpt2", "minigpt_base"
LABEL = {V4: "Foundation v4 base (98M)", GPT2: "GPT-2 (124M)", M34: "MiniGPT base (34M)"}
CONDITION_1_TASKS = ["hellaswag", "piqa", "lambada_openai", "arc_easy", "sciq"]
OUT_JSON = os.path.join(ROOT, "phase17/results/criteria_17b.json")
OUT_MD = os.path.join(ROOT, "phase17/results/TABLES_17B.md")


def diff(a, b):
    d = a["value"] - b["value"]
    se = math.sqrt(a["stderr"] ** 2 + b["stderr"] ** 2)
    return d, se


def main():
    subprocess.run([sys.executable, "subset_scores.py"], cwd=os.path.join(ROOT, "phase18"), check=True, capture_output=True)
    rnd = json.load(open(os.path.join(ROOT, "phase18/results/random_baselines.json")))
    res = {m: r18.load_model(m) for m in (V4, GPT2, M34)}
    cells = {m: {t: r18.cell(res[m], t, metric) for t, metric in r18.TASKS} for m in res}
    missing = [(m, t) for m in cells for t, c in cells[m].items() if c is None]
    if missing:
        raise SystemExit(f"missing results: {missing}")

    comp = {}
    for t, _ in r18.TASKS:
        d, se = diff(cells[V4][t], cells[GPT2][t])
        comp[t] = {"v4": cells[V4][t]["value"], "gpt2": cells[GPT2][t]["value"], "diff": d, "se_diff": se,
                   "significantly_better": d > 2 * se, "significantly_worse": -d > 2 * se}
    better = [t for t in CONDITION_1_TASKS if comp[t]["significantly_better"]]
    worse = [t for t, _ in r18.TASKS if comp[t]["significantly_worse"]]
    arc_c = cells[V4]["arc_challenge"]
    above = (arc_c["value"] - rnd["arc_challenge"]) > 2 * arc_c["stderr"]
    verdict = {
        "condition_1": {"rule": "significantly better than GPT-2 (> 2 stderr) on at least 3 of HellaSwag, PIQA, LAMBADA, ARC-Easy, SciQ",
                        "significantly_better_on": better, "count": len(better), "pass": len(better) >= 3},
        "condition_2": {"rule": "significantly worse than GPT-2 on none of the 12 tasks", "significantly_worse_on": worse, "pass": not worse},
        "condition_3": {"rule": "significantly above random on ARC-Challenge", "v4": arc_c["value"], "stderr": arc_c["stderr"], "random": rnd["arc_challenge"],
                        "margin_in_stderr": (arc_c["value"] - rnd["arc_challenge"]) / arc_c["stderr"], "pass": above},
    }
    verdict["success"] = all(v["pass"] for v in verdict.values() if isinstance(v, dict))

    vs34 = {}
    for t, _ in r18.TASKS:
        d, se = diff(cells[V4][t], cells[M34][t])
        vs34[t] = {"v4": cells[V4][t]["value"], "minigpt_34m": cells[M34][t]["value"], "diff": d, "se_diff": se, "significant": abs(d) > 2 * se}

    os.makedirs(os.path.dirname(OUT_JSON), exist_ok=True)
    json.dump({"criteria": "phase17/CRITERIA_17B.md", "verdict": verdict, "vs_gpt2": comp, "vs_minigpt_34m": vs34, "cells": cells, "random": rnd}, open(OUT_JSON, "w"), indent=2)

    def fmt(c, t):
        mark = "†" if (c["value"] - rnd[t]) <= 2 * c["stderr"] else ""
        return f"{100 * c['value']:.1f} ± {100 * c['stderr']:.1f}{mark}"

    lines = ["| Task | Random | " + " | ".join(LABEL[m] for m in (V4, GPT2, M34)) + " | v4 − GPT-2 | v4 vs GPT-2 | v4 − 34M | v4 vs 34M |",
             "| :--- | ---: | ---: | ---: | ---: | ---: | :--- | ---: | :--- |"]
    for t, _ in r18.TASKS:
        g, s = comp[t], vs34[t]
        gw = "better" if g["significantly_better"] else ("worse" if g["significantly_worse"] else "not significant")
        sw = ("better" if s["diff"] > 0 else "worse") if s["significant"] else "not significant"
        lines.append(f"| {r18.LABEL[t]} | {100 * rnd[t]:.1f} | {fmt(cells[V4][t], t)} | {fmt(cells[GPT2][t], t)} | {fmt(cells[M34][t], t)} | "
                     f"{100 * g['diff']:+.1f} ± {100 * g['se_diff']:.1f} | {gw} | {100 * s['diff']:+.1f} ± {100 * s['se_diff']:.1f} | {sw} |")
    md = ["# Phase 17B tables (generated by phase17/report_17b.py)", "",
          "Percent ± one standard error. † = not significantly above random (at most 2 standard errors above it). "
          "Comparisons: difference ± its standard error sqrt(se1² + se2²); significant when |difference| > 2 × that.", "", *lines, "",
          "## CRITERIA_17B.md verdict", "",
          f"- Condition 1 (better than GPT-2 on ≥ 3 of HellaSwag, PIQA, LAMBADA, ARC-Easy, SciQ): significantly better on {len(better)} "
          f"({', '.join(r18.LABEL[t] for t in better) or 'none'}) — **{'PASS' if verdict['condition_1']['pass'] else 'FAIL'}**",
          f"- Condition 2 (significantly worse than GPT-2 on none of 12): worse on {len(worse)} ({', '.join(r18.LABEL[t] for t in worse) or 'none'}) "
          f"— **{'PASS' if verdict['condition_2']['pass'] else 'FAIL'}**",
          f"- Condition 3 (ARC-Challenge significantly above random): {100 * arc_c['value']:.1f} ± {100 * arc_c['stderr']:.1f} vs {100 * rnd['arc_challenge']:.2f} "
          f"({verdict['condition_3']['margin_in_stderr']:.2f} standard errors above) — **{'PASS' if above else 'FAIL'}**",
          f"- **Success: {'YES' if verdict['success'] else 'NO'}**", ""]
    open(OUT_MD, "w").write("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
